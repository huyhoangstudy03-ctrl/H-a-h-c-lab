export function findReactionForPair(
  substanceAId: string,
  substanceBId: string,
): LabReactionPreset | null {
  return (
    LAB_REACTIONS.find(
      (r) =>
        (r.reactantAId === substanceAId && r.reactantBId === substanceBId) ||
        (r.reactantAId === substanceBId && r.reactantBId === substanceAId),
    ) ?? null
  );
}
